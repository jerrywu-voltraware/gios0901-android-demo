/// Shared UI and diagnostic text. Kept pure Dart for offline replay tools.
class AppTranslations {
  static String language = 'en';
  static const supportedLanguages = ['en', 'zh_TW'];
}

String tr(String source, [List<Object?> args = const []]) {
  final template =
      AppTranslations.language == 'zh_TW'
          ? source
          : englishMessages[source] ?? source;
  return template.replaceAllMapped(RegExp(r'\{(\d+)\}'), (match) {
    final index = int.parse(match[1]!);
    return index < args.length ? '${args[index]}' : match[0]!;
  });
}

